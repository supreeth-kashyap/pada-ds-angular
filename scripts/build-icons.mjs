// Generates the built-in icon registry (projects/pada-ds/src/lib/icon/icons.generated.ts) from
// projects/pada-ds/src/assets/icons/*.svg, the same SVGs as pada-ds. Run after adding an icon:
//
//   npm run icons:build
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(rootDir, 'projects/pada-ds/src/assets/icons');
const outFile = path.join(rootDir, 'projects/pada-ds/src/lib/icon/icons.generated.ts');

const files = (await readdir(iconsDir)).filter((file) => file.endsWith('.svg')).sort();
const entries = [];
for (const file of files) {
  const markup = (await readFile(path.join(iconsDir, file), 'utf8'))
    .replace(/<\?xml[^>]*>/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/>\s+</g, '><')
    .replace(/\s+/g, ' ')
    .trim();
  entries.push(`  ${JSON.stringify(file.replace(/\.svg$/, ''))}: ${JSON.stringify(markup)},`);
}

await writeFile(
  outFile,
  `// Generated by scripts/build-icons.mjs from src/assets/icons; do not edit.\n` +
    `export const BUILT_IN_ICONS: Readonly<Record<string, string>> = {\n${entries.join('\n')}\n};\n`,
  'utf8',
);
console.log(`Wrote ${files.length} icons to ${path.relative(rootDir, outFile)}`);
